import { useSyncExternalStore } from 'react';

export const getLanguage = () => {
  if (typeof window === 'undefined') return 'en';
  const value = window.localStorage.getItem('carmen_language');
  return ['en', 'th'].includes(value) ? value : 'en';
};
const subscribe = (listener) => {
  window.addEventListener('carmen-language-changed', listener);
  window.addEventListener('storage', listener);
  return () => {
    window.removeEventListener('carmen-language-changed', listener);
    window.removeEventListener('storage', listener);
  };
};
export const getLocale = () => ({ en: 'en-US', th: 'th-TH-u-ca-gregory' })[getLanguage()];
export const useLanguage = () => useSyncExternalStore(subscribe, getLanguage, () => 'en');
export const useTranslation = () => {
  const language = useLanguage();
  return (text, values) => translate(text, language, values);
};
export const translate = (text, language = getLanguage(), values) => {
  const translated = language === 'th' && Object.hasOwn(thai, text) ? thai[text] : text;
  return typeof translated === 'string' && values
    ? translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match)
    : translated;
};

